-- ============================================================================
-- 020 - Registro de clientes (consentimiento de promos)
-- ============================================================================
-- Que hace:
--   1. Agrega a clientes: apellido, acepta_promos, acepta_promos_en,
--      registrado_en y origen. No toca columnas existentes ni el trigger
--      pm_pedidos_actualizar_clientes().
--   2. registro_intentos: tabla anti-spam (sin acceso para clientes).
--   3. registrar_cliente(): alta/actualizacion de un registro desde la web.
--      Devuelve solo {ok:true} o un mensaje generico: nunca datos guardados.
--   4. borrar_mis_datos(): retira el consentimiento y, si el cliente nunca
--      pidio, borra su registro. No borra pedidos.
--   5. crear_pedido pasa de 14 a 15 argumentos (p_acepta_promos).
--
-- Prerequisitos: 010 a 019 aplicadas.
--
-- Acceso a clientes (confirmado, no se cambia):
--   - 011 hace revoke all a anon y authenticated y deja un unico GRANT SELECT
--     de tabla a authenticated; 017 deja la policy "Clientes lectura admin"
--     en es_dueno(). Las columnas nuevas quedan cubiertas por esa misma RLS:
--     solo el dueno las lee; anon no tiene ningun acceso; nadie escribe
--     directo (solo funciones SECURITY DEFINER). No se agregan grants.
--
-- NOTAS PARA EL CRM / ANALISIS:
--   - origen NO cambia si un cliente se registra y despues pide (ni al
--     reves): refleja como se creo la fila por primera vez. Para medir
--     clientes frecuentes o inactivos NO usar origen: filtrar por
--     cantidad_pedidos_entregados > 0 (y ultima_visita).
--   - Los clientes que ya existian y los que crea el trigger de pedidos
--     quedan con origen = 'pedido' (default de la columna).
--   - Un registro sin pedidos tiene cantidad_pedidos_entregados = 0 y
--     ultima_visita null.
--
-- LIMITACIONES CONOCIDAS:
--   - No hay verificacion de titularidad del telefono: cualquiera que sepa
--     un numero puede registrarlo o retirar su consentimiento / borrar un
--     registro sin pedidos. Riesgo bajo: las funciones no devuelven datos y
--     tienen anti-spam. Si hace falta, verificar con un codigo por WhatsApp.
--   - borrar_mis_datos conserva nombre y apellido de clientes que ya
--     pidieron (son datos de sus pedidos); solo retira el consentimiento.
--
-- IMPORTANTE: hacer BACKUP de la base antes de aplicar esta migracion.
-- Idempotente: se puede ejecutar mas de una vez.
-- ============================================================================

