function seleccionarVariacion(variacionId) {
  if (!productoEnPersonalizacion) return;
  const variaciones = obtenerVariacionesModal(productoEnPersonalizacion);
  if (!variaciones || !Array.isArray(variaciones.opciones)) return;
  const opt = variaciones.opciones.find(o => o.id === variacionId);
  if (opt) {
    opcionesSeleccionadas.variaciones = opt;
    actualizarPrecioModalPersonalizacion();
  }
}

function toggleAdicional(adicionalId) {
  if (!productoEnPersonalizacion || categoriaRequiereSoloPan(productoEnPersonalizacion)) return;
  const add = productoEnPersonalizacion.adicionales.find(a => a.id === adicionalId);
  if (!add) return;

  const idx = opcionesSeleccionadas.adicionales.findIndex(a => a.id === adicionalId);
  if (idx > -1) {
    opcionesSeleccionadas.adicionales.splice(idx, 1);
  } else {
    opcionesSeleccionadas.adicionales.push(add);
  }
  actualizarPrecioModalPersonalizacion();
}

function actualizarPrecioModalPersonalizacion() {
  if (!productoEnPersonalizacion) return;

  let precioUnitario = obtenerPrecioProducto(productoEnPersonalizacion, cartaActualSucursalId);

  if (opcionesSeleccionadas.variaciones) {
    precioUnitario += (opcionesSeleccionadas.variaciones.precio || 0);
  }

  const extraToppings = opcionesSeleccionadas.adicionales.reduce((acc, item) => acc + item.precio, 0);
  const unitarioFinal = precioUnitario + extraToppings;
  const totalConCantidad = unitarioFinal * cantidadPersonalizacion;

  const btnConfirmar = document.getElementById('btn-confirmar-adicionales');
  const validacionEl = document.getElementById('adicionales-validacion');

  const variaciones = obtenerVariacionesModal(productoEnPersonalizacion);
  const esObligatorio = !!(variaciones && variaciones.obligatorio);
  const tieneSeleccion = !!opcionesSeleccionadas.variaciones;

  if (esObligatorio && !tieneSeleccion) {
    if (btnConfirmar) {
      btnConfirmar.disabled = true;
      btnConfirmar.textContent = 'ELEGÍ UNA OPCIÓN PARA CONTINUAR';
    }
    if (validacionEl) validacionEl.hidden = false;
  } else {
    if (btnConfirmar) {
      btnConfirmar.disabled = false;
      btnConfirmar.textContent = `AGREGAR ${cantidadPersonalizacion} AL PEDIDO — ${formatearPrecioAR(totalConCantidad)}`;
    }
    if (validacionEl) validacionEl.hidden = true;
  }
}

