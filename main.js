function normalizarDescuentosPagoConfig(valor) {
  let datos = valor;
  if (typeof datos === 'string') {
    try { datos = JSON.parse(datos); } catch (error) { return null; }
  }
  if (!datos || typeof datos !== 'object' || Array.isArray(datos)) return null;

  const resultado = {};
  let encontrado = false;
  Object.keys(CONFIG_APP.pagos || {}).forEach((tipo) => {
    if (datos[tipo] === undefined || datos[tipo] === null) return;
    resultado[tipo] = normalizarDescuentoPago(datos[tipo]);
    encontrado = true;
  });
  return encontrado ? resultado : null;
}

function aplicarDescuentosPagoConfig(descuentos) {
  if (!descuentos) return false;
  Object.keys(descuentos).forEach((tipo) => {
    if (!CONFIG_APP.pagos[tipo]) return;
    CONFIG_APP.pagos[tipo].descuentoPorcentaje = normalizarDescuentoPago(descuentos[tipo]);
  });
  return true;
}

function cargarDescuentosPagoNube() {
  if (descuentosPagoNube) return Promise.resolve(descuentosPagoNube);
  if (descuentosPagoNubePromise) return descuentosPagoNubePromise;

  descuentosPagoNubePromise = (async () => {
    try {
      await cargarConfigNube();
      const clienteNube = obtenerClienteNube();
      if (!clienteNube) return null;
      const { data, error } = await conTiempoLimite(
        clienteNube
          .from('config_negocio')
          .select('valor')
          .eq('clave', 'descuentos_pago')
          .maybeSingle(),
        6000
      );
      if (error || !data) return null;
      return normalizarDescuentosPagoConfig(data.valor);
    } catch (error) {
      console.warn('No se pudieron leer los descuentos de pago desde config_negocio.', error);
      return null;
    }
  })();

  return descuentosPagoNubePromise.then(
    (descuentos) => {
      descuentosPagoNubePromise = null;
      if (descuentos) descuentosPagoNube = descuentos;
      return descuentos;
    },
    () => {
      descuentosPagoNubePromise = null;
      return null;
    }
  );
}

function normalizarConfiguracionApp(datos) {
  const base = crearConfiguracionAppPorDefecto();
  if (datos && datos.negocio) {
    if (typeof datos.negocio.nombre === 'string' && datos.negocio.nombre.trim()) {
      base.negocio.nombre = datos.negocio.nombre.trim();
    }
    if (typeof datos.negocio.ciudad === 'string' && datos.negocio.ciudad.trim()) {
      base.negocio.ciudad = datos.negocio.ciudad.trim();
    }
  }
  if (datos && datos.pagos && typeof datos.pagos === 'object') {
    Object.keys(base.pagos).forEach((tipo) => {
      const pago = datos.pagos[tipo];
      if (!pago || typeof pago !== 'object') return;
      if (typeof pago.etiqueta === 'string' && pago.etiqueta.trim()) base.pagos[tipo].etiqueta = pago.etiqueta.trim();
      if (typeof pago.emoji === 'string') base.pagos[tipo].emoji = pago.emoji.trim();
      if (pago.descuentoPorcentaje !== undefined) {
        base.pagos[tipo].descuentoPorcentaje = normalizarDescuentoPago(pago.descuentoPorcentaje);
      }
    });
  }
  return base;
}

function aplicarConfiguracionMarca() {
  const nombre = CONFIG_APP.negocio.nombre || 'Piedra Mora';
  const ciudad = CONFIG_APP.negocio.ciudad || '';
  document.querySelectorAll('[data-marca]').forEach((elemento) => {
    elemento.textContent = elemento.hasAttribute('data-marca-mayusculas') ? nombre.toUpperCase() : nombre;
  });
  document.querySelectorAll('[data-marca-alt]').forEach((imagen) => {
    const prefijo = imagen.getAttribute('data-marca-alt');
    imagen.alt = [prefijo, nombre].filter(Boolean).join(' ');
  });
  document.querySelectorAll('meta[data-marca-meta]').forEach((meta) => {
    const prefijo = meta.getAttribute('data-marca-meta');
    meta.setAttribute('content', [prefijo, nombre].filter(Boolean).join(' '));
  });
  const footer = document.querySelector('[data-marca-footer]');
  if (footer) footer.textContent = `© ${new Date().getFullYear()} ${nombre}${ciudad ? ` - ${ciudad}` : ''}`;
}

