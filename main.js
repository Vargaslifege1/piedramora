function normalizarValorURL(valor) {
  return String(valor == null ? '' : valor)
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function resolverSucursalPorURL(valor) {
  const clave = normalizarValorURL(valor);
  if (!clave) return null;

  const sucursales = Object.values(SUCURSALES || {});
  for (const sucursal of sucursales) {
    if (!sucursal || !sucursal.id) continue;
    const candidatos = [
      sucursal.id,
      sucursal.nombre,
      sucursal.tituloCarta,
      ...(Array.isArray(sucursal.aliases) ? sucursal.aliases : []),
      ...String(sucursal.id).split('-')
    ]
      .map(normalizarValorURL)
      .filter(Boolean);

    const coincide = candidatos.some(candidato =>
      candidato === clave || candidato.startsWith(`${clave}-`) || clave.startsWith(`${candidato}-`)
    );
    if (coincide) return sucursal.id;
  }

  return null;
}

function normalizarModoURL(valor) {
  const modo = normalizarValorURL(valor);
  if (!modo) return null;
  if (['mesa', 'salon', 'mesa-salon', 'solo-carta', 'carta-mesa', 'table', 'dine-in'].includes(modo)) return 'mesa';
  if (['delivery', 'takeaway', 'retiro', 'delivery-takeaway', 'pedido', 'delivery-take-away'].includes(modo)) return 'delivery_takeaway';
  return null;
}

function leerAccesoDirectoURL() {
  const params = new URLSearchParams(window.location.search || '');
  const valorSucursal = params.get('sucursal') || params.get('local') || params.get('s') || params.get('branch') || '';
  const valorModo = params.get('modo') || params.get('mode') || params.get('tipo') || '';
  const mesaActiva = params.has('mesa') && !['0', 'false', 'no'].includes(normalizarValorURL(params.get('mesa')));
  const soloCarta = params.has('solo-carta') && !['0', 'false', 'no'].includes(normalizarValorURL(params.get('solo-carta')));

  modoCartaForzado = normalizarModoURL(valorModo) || (mesaActiva || soloCarta ? 'mesa' : null);

  return {
    sucursalId: resolverSucursalPorURL(valorSucursal),
    modo: modoCartaForzado
  };
}

