async function abrirCartaDosEtapas(sucursalId) {
  const sucursal = SUCURSALES[sucursalId];
  if (!sucursal) return;

  const cambiaDeSucursal = !!cartaActualSucursalId && cartaActualSucursalId !== sucursalId;
  if (cambiaDeSucursal && CARRITO.length > 0) {
    const sucursalAnterior = SUCURSALES[cartaActualSucursalId];
    const nombreAnterior = sucursalAnterior ? sucursalAnterior.nombre : 'otra sucursal';
    const decision = await confirmarAccion({
      titulo: 'Cambiar de sucursal',
      mensaje: `Tu carrito tiene productos de ${nombreAnterior}. Para pedir en ${sucursal.nombre} tenés que vaciarlo y empezar de nuevo.`,
      textoAceptar: 'Vaciar y cambiar',
      textoCancelar: 'Cancelar'
    });
    if (decision !== 'aceptar') {
      if (cartaAbierta && cartaActualSucursalId) {
        try { history.replaceState(null, '', `#carta-${cartaActualSucursalId}`); } catch (e) {}
      }
      return;
    }
    vaciarCarrito({ resetDireccion: true });
  } else if (cambiaDeSucursal) {
    resetearDireccionCheckout();
  }

  ultimoFoco = document.activeElement;
  trackearClicCarta('ver_carta', sucursalId, sucursal.nombre, {});

  const retomaCarrito = CARRITO.length > 0 && cartaActualSucursalId === sucursalId;
  const modalidadRetomada = retomaCarrito ? cartaModalidadSeleccionada : null;

  await cargarConfiguracionApp();
  const cargaCarta = await cargarCartaPorSucursal(sucursalId);
  if (!cargaCarta) await cargarCartasEnSegundoPlano();
  cartaActualSucursalId = sucursalId;
  cartaModalidadSeleccionada = modoCartaForzado || modalidadRetomada;
  actualizarAvisoPrivacidad();
  programarCotizacionEnvio();

  if (modoCartaForzado === 'mesa') {
    CARRITO = [];
    resetearDireccionCheckout();
  }

  const categoriasConProds = obtenerCategoriasYSusProductosPorSucursal(sucursalId);
  cartaActualData = { categorias: categoriasConProds };

  if (cartaTituloSucursalEl) {
    cartaTituloSucursalEl.textContent = sucursal.tituloCarta || sucursal.nombre;
  }

  cartaRequiereModalidad = !!sucursal.requiereModalidad;
  aplicarModoVisualizacionCarta();

  categoriaActivaIndex = -1;
  if (cartaProductosLista) cartaProductosLista.innerHTML = '';
  if (cartaTituloCategoriaActiva) cartaTituloCategoriaActiva.textContent = '';

  const navCat = document.querySelector('.carta-navegacion-categorias');
  if (navCat) navCat.style.display = 'none';

  if (cartaRequiereModalidad && !cartaModalidadSeleccionada) {
    if (cartaEtapaCategorias) cartaEtapaCategorias.classList.remove('carta-etapa-activa');
    if (cartaEtapaProductos) cartaEtapaProductos.classList.remove('carta-etapa-activa');
    mostrarEtapaModalidad();
    if (cartaListaCategoriasVertical) cartaListaCategoriasVertical.innerHTML = '';
  } else {
    mostrarEtapaCategorias();
    renderCategoriasVertical();
  }

  abrirCartaUI();
  try { history.pushState(null, '', `#carta-${sucursalId}`); } catch (e) {}
}

