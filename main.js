async function solicitarCerrarCarta(e) {
  if (e && typeof e.preventDefault === 'function') e.preventDefault();
  if (e && typeof e.stopPropagation === 'function') e.stopPropagation();
  if (!cartaAbierta || confirmandoCierreCarta) return;

  if (CARRITO.length === 0) {
    cerrarCarta();
    return;
  }

  const totalItems = CARRITO.reduce((acc, item) => acc + item.cantidad, 0);
  const totalPrecio = CARRITO.reduce((acc, item) => acc + (item.precio * item.cantidad), 0);
  const detalle = `${totalItems} ${totalItems === 1 ? 'producto' : 'productos'} por ${formatearPrecioAR(totalPrecio)}`;
  confirmandoCierreCarta = true;
  const decision = await confirmarAccion({
    titulo: '¿Vaciar el carrito y salir?',
    mensaje: `Tenés ${detalle}. Podés vaciarlo o conservarlo para retomarlo después desde el acceso flotante.`,
    textoAceptar: 'Vaciar y salir',
    textoCancelar: 'Conservar carrito'
  });
  confirmandoCierreCarta = false;
  if (!decision) return;

  if (decision === 'aceptar') vaciarCarrito();
  cerrarCarta();
}

function cerrarCarta(e) {
  if (e && typeof e.preventDefault === 'function') e.preventDefault();
  if (e && typeof e.stopPropagation === 'function') e.stopPropagation();
  if (!cartaAbierta) return;
  cartaCerrandoProgramaticamente = true;
  cartaAbierta = false;
  if (cartaPanel) { cartaPanel.hidden = true; cartaPanel.classList.remove('abierto'); }
  if (cartaOverlay) { cartaOverlay.hidden = true; cartaOverlay.classList.remove('visible'); }
  if (cartaEtapaModalidad) cartaEtapaModalidad.classList.remove('carta-etapa-activa');
  if (cartaEtapaCategorias) cartaEtapaCategorias.classList.remove('carta-etapa-activa');
  if (cartaEtapaProductos) cartaEtapaProductos.classList.remove('carta-etapa-activa');
  try { fidelidadSetEtapaVisible(false); } catch (e) {}
  if (CARRITO.length === 0) cartaModalidadSeleccionada = null;
  cartaRequiereModalidad = false;
  document.body.classList.remove('carta-modo-mesa');
  const navCatClose = document.querySelector('.carta-navegacion-categorias');
  if (navCatClose) navCatClose.style.display = 'none';
  const destinoScroll = (typeof cartaOrigenScrollY === 'number') ? cartaOrigenScrollY : scrollYActual;
  desbloquearScrollFondo();
  if (typeof destinoScroll === 'number') {
    try { window.scrollTo({ top: destinoScroll, left: 0, behavior: 'auto' }); } catch (e3) {
      try { window.scrollTo(0, destinoScroll); } catch (e4) {}
    }
  }
  cartaOrigenScrollY = null;
  try {
    if (history.replaceState) {
      history.replaceState(null, '', window.location.pathname + window.location.search);
    }
  } catch (e2) {}
  if (ultimoFoco && typeof ultimoFoco.focus === 'function') {
    try { ultimoFoco.focus(); } catch (e5) {}
  }
  actualizarAccesoCarritoGlobal();
  setTimeout(() => { cartaCerrandoProgramaticamente = false; }, 50);
}

