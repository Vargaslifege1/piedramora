function obtenerClienteNube() {
  if (nubeCliente) return nubeCliente;
  if (!NUBE_CONFIG) return null;

  const api = window.supabase;
  if (!api || typeof api.createClient !== 'function') return null;

  nubeCliente = api.createClient(NUBE_CONFIG.supabaseUrl, NUBE_CONFIG.supabaseAnonKey, {
    auth: {
      persistSession: false,
      autoRefreshToken: false,
      detectSessionInUrl: false
    }
  });

  return nubeCliente;
}

async function cargarCartaDesdeNube() {
  await cargarConfigNube();
  const cliente = obtenerClienteNube();
  if (!cliente || !NUBE_CONFIG) return null;

  const tabla = NUBE_CONFIG.tabla || 'carta';
  const filaId = NUBE_CONFIG.filaId !== undefined ? NUBE_CONFIG.filaId : 1;

  const { data, error } = await cliente
    .from(tabla)
    .select('contenido')
    .eq('id', filaId)
    .maybeSingle();

  if (error) {
    console.warn('No se pudo leer la carta desde Supabase:', error.message);
    return null;
  }

  if (!data || !data.contenido) return null;
  return data.contenido;
}

function iniciarSuscripcionNube() {
  if (nubeSuscripcion || !NUBE_CONECTADA || !NUBE_CONFIG) return;
  const cliente = obtenerClienteNube();
  if (!cliente) return;

  const tabla = NUBE_CONFIG.tabla || 'carta';
  const filaId = NUBE_CONFIG.filaId !== undefined ? NUBE_CONFIG.filaId : 1;

  nubeSuscripcion = cliente
    .channel(`piedra-mora-carta-${tabla}`)
    .on('postgres_changes', {
      event: '*',
      schema: 'public',
      table: tabla,
      filter: `id=eq.${filaId}`
    }, (payload) => {
      if (payload && payload.new && payload.new.contenido) {
        aplicarCartaRemota(payload.new.contenido);
      }
    })
    .subscribe((estado) => {
      if (estado === 'CHANNEL_ERROR' || estado === 'TIMED_OUT') {
        console.warn('Realtime de la carta no disponible:', estado);
      }
    });
}

