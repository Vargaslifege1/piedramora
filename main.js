function iniciarSuscripcionNube() {
  if (nubeSuscripcion || !NUBE_CONECTADA || !NUBE_CONFIG) return;
  const cliente = obtenerClienteNube();
  if (!cliente) return;

  const tabla = NUBE_CONFIG.tabla || 'carta';
  const filaId = NUBE_CONFIG.filaId !== undefined ? NUBE_CONFIG.filaId : 1;

  nubeSuscripcion = cliente
    .channel(`piedra-mora-carta-${tabla}`)
    .on('postgres_changes', {
      event: '*',
      schema: 'public',
      table: tabla,
      filter: `id=eq.${filaId}`
    }, (payload) => {
      if (payload && payload.new && payload.new.contenido) {
        if (cartaActualSucursalId && (cartaAbierta || CARRITO.length > 0)) {
          refrescarCartaActual();
        } else {
          aplicarCartaRemota(payload.new.contenido);
        }
      }
    })
    .subscribe((estado) => {
      if (estado === 'CHANNEL_ERROR' || estado === 'TIMED_OUT') {
        console.warn('Realtime de la carta no disponible:', estado);
      }
    });
}

function aplicarCartaRemota(datos) {
  const nuevosDatos = normalizarDatosCarta(datos);
  const categoriaActivaId = (cartaActualData && categoriaActivaIndex >= 0 && cartaActualData.categorias[categoriaActivaIndex])
    ? cartaActualData.categorias[categoriaActivaIndex].id
    : null;

  CARTAS_UNIFICADAS = nuevosDatos;
  CARTA_CACHE_LOADED = true;

  if (!cartaActualSucursalId) return;
  if (cartaRequiereModalidad && !cartaModalidadSeleccionada) return;

  const categorias = obtenerCategoriasYSusProductosPorSucursal(cartaActualSucursalId);
  cartaActualData = { categorias };

  categoriaActivaIndex = categoriaActivaId
    ? categorias.findIndex(cat => cat.id === categoriaActivaId)
    : -1;

  renderCategoriasVertical();
  renderCategoriasHoriz();

  if (categoriaActivaIndex >= 0) {
    renderProductosCategoria(categorias[categoriaActivaIndex]);
  } else {
    if (cartaProductosLista) cartaProductosLista.innerHTML = '';
    if (cartaTituloCategoriaActiva) cartaTituloCategoriaActiva.textContent = '';
    if (cartaEtapaProductos && cartaEtapaProductos.classList.contains('carta-etapa-activa')) {
      mostrarEtapaCategorias();
    }
  }

  recalcularPreciosCarrito();
  actualizarBotonFlotanteWhatsapp();

  const checkoutPanel = document.getElementById('checkout-panel');
  if (checkoutPanel && !checkoutPanel.hidden) {
    renderizarListaCheckout();
  }
}

