function abrirDesdeHash() {
  const hash = window.location.hash;
  if (!hash) return;
  const rest = hash.replace(/^#carta-/, '');
  if (!rest) return;
  const sucIds = Object.keys(SUCURSALES || {});
  let sucursalId = null;
  for (let i = 0; i < sucIds.length; i++) {
    const sid = sucIds[i];
    if (rest === sid || rest.startsWith(sid + '-')) {
      sucursalId = sid;
      break;
    }
  }
  if (!sucursalId || !SUCURSALES[sucursalId]) return;
  cargarCartasEnSegundoPlano().then(() => {
    abrirCartaPorSucursal(sucursalId);
  });
}

