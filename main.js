function centrarCategoriaHorizActiva(behavior = 'smooth') {
  if (!cartaCategoriasHoriz) return;
  const activa = cartaCategoriasHoriz.querySelector('.carta-categoria-horiz-btn.activa');
  if (!activa) return;

  if (behavior === 'smooth' && typeof window.matchMedia === 'function' && window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
    behavior = 'auto';
  }

  const contRect = cartaCategoriasHoriz.getBoundingClientRect();
  const btnRect = activa.getBoundingClientRect();
  const desplazamiento = (btnRect.left - contRect.left) - ((contRect.width - btnRect.width) / 2);
  const destino = Math.max(0, cartaCategoriasHoriz.scrollLeft + desplazamiento);

  if (typeof cartaCategoriasHoriz.scrollTo === 'function') {
    cartaCategoriasHoriz.scrollTo({ left: destino, behavior });
  } else {
    cartaCategoriasHoriz.scrollLeft = destino;
  }
}

function renderCategoriasHoriz() {
  if (!cartaCategoriasHoriz) return;
  cartaCategoriasHoriz.innerHTML = '';

  if (!cartaActualData || !cartaActualData.categorias) return;

  cartaActualData.categorias.forEach((cat, idx) => {
    const btn = document.createElement('button');
    btn.type = 'button';
    btn.className = 'carta-categoria-horiz-btn';
    btn.setAttribute('role', 'tab');
    btn.setAttribute('aria-selected', 'false');
    btn.textContent = cat.nombre;
    btn.dataset.idx = String(idx);

    btn.addEventListener('click', () => {
      cartaCategoriasHoriz.querySelectorAll('.carta-categoria-horiz-btn').forEach(b => {
        b.classList.remove('activa');
        b.setAttribute('aria-selected', 'false');
      });
      btn.classList.add('activa');
      btn.setAttribute('aria-selected', 'true');
      categoriaActivaIndex = idx;
      renderProductosCategoria(cat);
      const contenedor = document.querySelector('.carta-productos-contenedor');
      if (contenedor) contenedor.scrollTop = 0;
      centrarCategoriaHorizActiva();
    });

    btn.addEventListener('keydown', (e) => {
      const botones = Array.from(cartaCategoriasHoriz.querySelectorAll('.carta-categoria-horiz-btn'));
      const posicion = botones.indexOf(btn);
      let destino = null;

      if (e.key === 'ArrowRight') destino = botones[(posicion + 1) % botones.length];
      if (e.key === 'ArrowLeft') destino = botones[(posicion - 1 + botones.length) % botones.length];
      if (e.key === 'Home') destino = botones[0];
      if (e.key === 'End') destino = botones[botones.length - 1];

      if (destino) {
        e.preventDefault();
        destino.click();
        destino.focus();
      }
    });

    cartaCategoriasHoriz.appendChild(btn);
  });

  if (categoriaActivaIndex >= 0 && cartaCategoriasHoriz.children[categoriaActivaIndex]) {
    const activa = cartaCategoriasHoriz.children[categoriaActivaIndex];
    activa.classList.add('activa');
    activa.setAttribute('aria-selected', 'true');
    requestAnimationFrame(() => centrarCategoriaHorizActiva('auto'));
  }
}

