function obtenerCategoriaId(prod) {
  return String(prod && prod.categoria ? prod.categoria : '').trim().toLowerCase();
}

function esCategoriaPizza(prod) {
  return obtenerCategoriaId(prod) === 'pizza';
}

function esCategoriaPromo(prod) {
  return obtenerCategoriaId(prod) === 'promo';
}

function categoriaRequiereSoloPan(prod) {
  return CATEGORIAS_SOLO_PAN.has(obtenerCategoriaId(prod));
}

function obtenerVariacionesModal(prod) {
  if (!prod || !categoriaRequiereSoloPan(prod)) {
    return prod && prod.variaciones ? prod.variaciones : null;
  }

  const opcionesPan = Array.isArray(prod.variaciones && prod.variaciones.opciones)
    ? prod.variaciones.opciones.filter(opt => /pan|franc|arabe|árabe/i.test(`${opt.id || ''} ${opt.nombre || ''}`))
    : [];

  return {
    titulo: 'Elegí el tipo de pan',
    obligatorio: true,
    opciones: opcionesPan.length >= 2
      ? opcionesPan
      : OPCIONES_PAN_PREDETERMINADAS.map(opt => ({
        ...opt,
        id: PM.generarIdOpcion(prod.id, opt.id)
      }))
  };
}

function productoPermitePersonalizacion(prod) {
  if (!prod || esCategoriaPizza(prod) || esCategoriaPromo(prod)) return false;
  if (categoriaRequiereSoloPan(prod)) return true;

  const tieneVariaciones = !!(prod.variaciones && Array.isArray(prod.variaciones.opciones) && prod.variaciones.opciones.length > 0);
  const tieneAdicionales = !!(prod.adicionales && Array.isArray(prod.adicionales) && prod.adicionales.length > 0);
  return tieneVariaciones || tieneAdicionales;
}

function obtenerEspecificacionesLinea(linea) {
  const partes = [];
  if (linea.variacion && linea.variacion.nombre) partes.push(linea.variacion.nombre);
  if (Array.isArray(linea.adicionalesLista) && linea.adicionalesLista.length > 0) {
    linea.adicionalesLista.forEach((adicional) => partes.push(adicional.nombre));
  } else if (Array.isArray(linea.detallesExtras) && linea.detallesExtras.length > 0) {
    linea.detallesExtras.forEach((detalle) => partes.push(detalle));
  }
  return partes;
}

