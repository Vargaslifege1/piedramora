function actualizarLineaEnvio() {
  const linea = document.getElementById('linea-envio');
  const valor = document.getElementById('checkout-envio');
  const detalle = document.getElementById('checkout-envio-detalle');

  if (!linea) return { visible: false, costo: 0 };

  if (!checkoutEsDelivery()) {
    linea.hidden = true;
    linea.style.display = 'none';
    return { visible: false, costo: 0 };
  }

  linea.hidden = false;
  linea.style.display = 'flex';

  if (!tieneDireccionConfirmada()) {
    if (valor) valor.textContent = 'Se calcula con tu direcci\u00f3n';
    if (detalle) detalle.textContent = '';
    return { visible: true, costo: 0 };
  }

  if (envioCotizado) {
    const costo = Math.max(0, Number(envioCotizado.costo_envio) || 0);
    const cuadras = Number(envioCotizado.cuadras);
    if (valor) valor.textContent = formatearPrecioAR(costo);
    if (detalle) {
      detalle.textContent = Number.isFinite(cuadras) && cuadras > 0
        ? `a ${cuadras} cuadra${cuadras === 1 ? '' : 's'} de la sucursal`
        : '';
    }
    return { visible: true, costo };
  }

  if (envioCotizando) {
    if (valor) valor.textContent = 'Calculando...';
    if (detalle) detalle.textContent = '';
    return { visible: true, costo: 0 };
  }

  if (valor) valor.textContent = 'A confirmar';
  if (detalle) detalle.textContent = '';
  return { visible: true, costo: 0 };
}

function actualizarResumenPago(subtotal) {
  const totales = calcularTotalesPedido(subtotal);
  const elPago = document.getElementById('checkout-pago-seleccionado');
  const elDescuento = document.getElementById('checkout-descuento');
  const elDescuentoLabel = document.getElementById('checkout-descuento-label');
  const elTotal = document.getElementById('checkout-total');
  const lineaDescuento = document.querySelector('.linea-total.linea-descuento');

  if (elPago) elPago.textContent = totales.pago.nombre;
  if (elDescuentoLabel) {
    elDescuentoLabel.textContent = totales.pago.porcentaje > 0
      ? `(${totales.pago.nombre} ${totales.pago.porcentaje}%)`
      : '';
  }
  if (elDescuento) {
    elDescuento.textContent = `- ${formatearPrecioAR(totales.descuento)}`;
  }

  const envio = actualizarLineaEnvio();
  let totalFinal = Math.max(0, totales.total + (envio.costo || 0));

  // Vista previa únicamente: valida_cupon ya compara server-side el descuento
  // del cupón contra el de medio de pago (gana el mayor, salvo acumulable), pero
  // no nos dice cuál ganó. Por eso en pantalla el cupón reemplaza la línea de
  // descuento por pago en vez de sumarse. El total real y definitivo siempre lo
  // decide crear_pedido en el servidor al confirmar el pedido.
  if (cuponAplicado) {
    totalFinal = Math.max(0, totales.subtotal - cuponAplicado.descuento + (envio.costo || 0));
  }
  // Premio de fidelidad: reemplaza el descuento por pago (el servidor ignora ambos si hay premio).
  if (premioElegido) {
    totalFinal = Math.max(0, totales.subtotal - fidelidadDescuentoPremio(totales.subtotal) + (envio.costo || 0));
  }
  if (elTotal) elTotal.textContent = formatearPrecioAR(totalFinal);
  try { fidelidadActualizarLineaPremio(); } catch (e) {}

  if (lineaDescuento) {
    const hayDescuento = totales.descuento > 0 && !cuponAplicado && !premioElegido;
    lineaDescuento.hidden = !hayDescuento;
    lineaDescuento.style.display = hayDescuento ? 'flex' : 'none'; // Se oculta completamente si no hay descuento
  }
  return { ...totales, costo_envio: envio.costo || 0, total: totalFinal };
}

