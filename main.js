function obtenerPrecioRegularProducto(prod) {
  if (!prod || !prod.precios) return 0;

  if (cartaModalidadSeleccionada === 'mesa') {
    return prod.precios.mesa !== undefined ? prod.precios.mesa : (prod.precios.delivery || 0);
  }

  return prod.precios.delivery !== undefined ? prod.precios.delivery : (prod.precios.mesa || 0);
}

function obtenerPrecioOfertaProducto(prod) {
  if (!prod) return null;

  if (!PM.ofertaVigente(prod)) return null;

  const clave = cartaModalidadSeleccionada === 'mesa' ? 'mesa' : 'delivery';
  let valor = prod[`${clave}_oferta`];

  if (valor === undefined || valor === null) {
    const claveAlterna = clave === 'mesa' ? 'delivery_oferta' : 'mesa_oferta';
    valor = prod[claveAlterna];
  }

  if ((valor === undefined || valor === null) && prod.preciosOferta) {
    valor = prod.preciosOferta[clave];
    if (valor === undefined || valor === null) {
      valor = prod.preciosOferta.delivery !== undefined
        ? prod.preciosOferta.delivery
        : prod.preciosOferta.mesa;
    }
  }

  if (valor === undefined || valor === null) return null;

  const precioOferta = Number(valor);
  if (!Number.isFinite(precioOferta) || precioOferta <= 0) return null;

  const precioRegular = Number(obtenerPrecioRegularProducto(prod)) || 0;
  if (precioRegular > 0 && precioOferta >= precioRegular) return null;

  return precioOferta;
}

function productoTieneOferta(prod) {
  return obtenerPrecioOfertaProducto(prod) !== null;
}

function obtenerTipoOfertaProducto(prod) {
  if (!productoTieneOferta(prod)) return null;
  const tipo = String((prod && prod.tipoOferta) || '').toLowerCase();
  if (tipo === 'semana') return 'semana';
  if (tipo === 'fecha') return 'fecha';
  return 'dia';
}

function obtenerTipoOfertaVisual(prod) {
  return obtenerTipoOfertaProducto(prod) === 'semana' ? 'semana' : 'dia';
}

function obtenerPrecioProducto(prod, sucursalId) {
  const precioOferta = obtenerPrecioOfertaProducto(prod);
  if (precioOferta !== null) return precioOferta;
  return obtenerPrecioRegularProducto(prod, sucursalId);
}

function obtenerEtiquetaOferta(prod) {
  const tipo = obtenerTipoOfertaProducto(prod);
  if (tipo === 'fecha') {
    const hasta = PM.fechaOfertaCorta(prod && prod.oferta_hasta);
    return hasta ? `Hasta el ${hasta}` : 'OFERTA';
  }
  return tipo === 'semana' ? '🔥 OFERTA DE LA SEMANA' : '⚡ OFERTA DEL DÍA';
}

