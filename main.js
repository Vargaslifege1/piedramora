function confirmarAccion(opciones = {}) {
  const overlay = document.getElementById('confirmacion-overlay');
  const panel = document.getElementById('confirmacion-panel');
  const tituloEl = document.getElementById('confirmacion-titulo');
  const mensajeEl = document.getElementById('confirmacion-mensaje');
  const aceptarBtn = document.getElementById('confirmacion-aceptar');
  const cancelarBtn = document.getElementById('confirmacion-cancelar');

  if (!overlay || !panel || !tituloEl || !mensajeEl || !aceptarBtn || !cancelarBtn) {
    const confirmado = typeof window.confirm === 'function' && window.confirm(opciones.mensaje || '');
    return Promise.resolve(confirmado ? 'aceptar' : null);
  }

  if (confirmacionResolver) resolverConfirmacion(null);

  return new Promise(resolve => {
    confirmacionFocoAnterior = document.activeElement;
    tituloEl.textContent = opciones.titulo || 'Confirmar acción';
    mensajeEl.textContent = opciones.mensaje || '';
    aceptarBtn.textContent = opciones.textoAceptar || 'Aceptar';
    cancelarBtn.textContent = opciones.textoCancelar || 'Cancelar';
    overlay.hidden = false;
    panel.hidden = false;
    document.body.classList.add('confirmacion-abierta');
    confirmacionResolver = resolve;
    requestAnimationFrame(() => {
      overlay.classList.add('visible');
      panel.classList.add('abierto');
    });
    setTimeout(() => {
      try { cancelarBtn.focus({ preventScroll: true }); } catch (e) {}
    }, 40);
  });
}

function resolverConfirmacion(resultado) {
  const resolver = confirmacionResolver;
  if (!resolver) return;
  confirmacionResolver = null;

  const overlay = document.getElementById('confirmacion-overlay');
  const panel = document.getElementById('confirmacion-panel');
  if (overlay) overlay.classList.remove('visible');
  if (panel) panel.classList.remove('abierto');
  document.body.classList.remove('confirmacion-abierta');
  setTimeout(() => {
    if (confirmacionResolver) return;
    if (overlay) overlay.hidden = true;
    if (panel) panel.hidden = true;
  }, 180);

  if (confirmacionFocoAnterior && typeof confirmacionFocoAnterior.focus === 'function') {
    try { confirmacionFocoAnterior.focus({ preventScroll: true }); } catch (e) {}
  }
  confirmacionFocoAnterior = null;
  resolver(resultado);
}

