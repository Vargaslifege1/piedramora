async function buscarDireccionPedix() {
  const input = document.getElementById('cliente-direccion-input');
  const query = input?.value.trim();
  const contLista = document.getElementById('pedix-lista-resultados');
  const contRadios = document.getElementById('pedix-radios-container');
  const btnBuscar = document.getElementById('btn-buscar-direccion');

  if (!query || query.length < 3) {
    mostrarEstadoBusquedaPedix('Ingresá al menos 3 caracteres para buscar.', 'error');
    input?.focus();
    return;
  }

  const coordsRef = obtenerCentroSucursalActiva();
  const claveCache = `${query.toLowerCase()}|${coordsRef.lat.toFixed(2)}|${coordsRef.lng.toFixed(2)}`;
  const token = ++pedixBusquedaToken;

  contLista.hidden = false;
  contRadios.innerHTML = '';
  const cargando = document.createElement('p');
  cargando.className = 'pedix-ayuda-texto';
  cargando.textContent = 'Buscando direcciones...';
  contRadios.appendChild(cargando);

  if (btnBuscar) {
    btnBuscar.disabled = true;
    btnBuscar.setAttribute('aria-busy', 'true');
  }
  mostrarEstadoBusquedaPedix('Buscando direcciones en Catamarca y alrededores...');

  try {
    let resultados = pedixCacheBusquedas.get(claveCache);

    if (!resultados) {
      let url = `https://nominatim.openstreetmap.org/search?format=jsonv2&q=${encodeURIComponent(query)}&countrycodes=ar&limit=12&addressdetails=1&accept-language=es`;
      const delta = 0.45;
      const minLng = coordsRef.lng - delta;
      const minLat = coordsRef.lat - delta;
      const maxLng = coordsRef.lng + delta;
      const maxLat = coordsRef.lat + delta;
      url += `&viewbox=${minLng},${maxLat},${maxLng},${minLat}`;

      const resp = await fetch(url, { headers: { Accept: 'application/json' } });
      if (!resp.ok) throw new Error(`Nominatim respondió ${resp.status}`);
      resultados = await resp.json();
      if (!Array.isArray(resultados)) resultados = [];
      pedixCacheBusquedas.set(claveCache, resultados);
    }

    if (token !== pedixBusquedaToken) return;

    const resultadosConDistancia = resultados
      .map((res) => {
        const lat = parseFloat(res.lat);
        const lng = parseFloat(res.lon);
        return {
          ...res,
          lat,
          lng,
          distancia: calcularDistanciaKm(coordsRef.lat, coordsRef.lng, lat, lng)
        };
      })
      .filter((res) => Number.isFinite(res.lat) && Number.isFinite(res.lng))
      .sort((a, b) => a.distancia - b.distancia)
      .slice(0, 6);

    contRadios.innerHTML = '';

    if (resultadosConDistancia.length === 0) {
      const sinResultados = document.createElement('p');
      sinResultados.className = 'pedix-ayuda-texto';
      sinResultados.textContent = 'No encontramos direcciones coincidentes. Probá con calle y número, o ubicá el punto manualmente en el mapa.';
      contRadios.appendChild(sinResultados);
      mostrarEstadoBusquedaPedix('Sin resultados. Podés marcar tu ubicación manualmente.', 'error');
      return;
    }

    resultadosConDistancia.forEach((res) => {
      const label = document.createElement('label');
      label.className = 'pedix-radio-item';

      const radio = document.createElement('input');
      radio.type = 'radio';
      radio.name = 'pedix_dir_option';
      radio.value = `${res.lat},${res.lng}`;

      const info = document.createElement('span');
      info.className = 'pedix-radio-info';

      const texto = document.createElement('span');
      texto.className = 'pedix-radio-texto';
      texto.textContent = res.display_name || 'Dirección sin nombre';

      const distancia = document.createElement('span');
      distancia.className = 'pedix-radio-distancia';
      distancia.textContent = `a ${res.distancia.toFixed(1).replace('.', ',')} km de la sucursal`;

      info.append(texto, distancia);
      label.append(radio, info);

      radio.addEventListener('change', () => {
        confirmarDireccionPedix({
          texto: res.display_name || 'Dirección seleccionada',
          lat: res.lat,
          lng: res.lng
        });
      });

      contRadios.appendChild(label);
    });

    mostrarEstadoBusquedaPedix(`Encontramos ${resultadosConDistancia.length} direcciones ordenadas por cercanía.`, 'ok');
  } catch (err) {
    if (token !== pedixBusquedaToken) return;
    console.error(err);
    contRadios.innerHTML = '';
    const error = document.createElement('p');
    error.className = 'pedix-ayuda-texto pedix-estado-error';
    error.textContent = 'No pudimos buscar direcciones en este momento. Revisá tu conexión o marcá el punto en el mapa.';
    contRadios.appendChild(error);
    mostrarEstadoBusquedaPedix('Error al buscar direcciones.', 'error');
  } finally {
    if (token === pedixBusquedaToken && btnBuscar) {
      btnBuscar.disabled = false;
      btnBuscar.removeAttribute('aria-busy');
    }
  }
}

function mostrarErrorCampo(input, error, mensaje) {
  if (input) {
    input.classList.add('campo-invalido');
    input.setAttribute('aria-invalid', 'true');
  }
  if (error) {
    error.textContent = mensaje;
    error.hidden = false;
  }
}

function limpiarErrorCampo(input, error) {
  if (input) {
    input.classList.remove('campo-invalido');
    input.removeAttribute('aria-invalid');
  }
  if (error) {
    error.textContent = '';
    error.hidden = true;
  }
}

