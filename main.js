function getFondoCategoria(cat) {
  const id = (cat.id || '').toLowerCase();
  const foto = typeof cat.foto === 'string' ? cat.foto.trim() : '';
  if (esRutaImagenSegura(foto)) return foto;
  if (CATEGORIA_FONDO[id]) return CATEGORIA_FONDO[id];
  return 'assets/logo.webp';
}

function obtenerTipoOfertaCategoria(cat) {
  let tipo = null;
  const productos = Array.isArray(cat.productos) ? cat.productos : [];

  productos.forEach(prod => {
    if (!productoTieneOferta(prod)) return;
    const tipoProd = obtenerTipoOfertaProducto(prod);
    if (tipoProd === 'semana') {
      if (tipo !== 'dia') tipo = 'semana';
    } else {
      tipo = 'dia';
    }
  });

  return tipo;
}

