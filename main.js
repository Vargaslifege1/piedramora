function alHacerClicAgregar(productoId) {
  if (!cartaPermitePedidos()) return;
  const prodObj = CARTAS_UNIFICADAS.productos.find(p => p.id === productoId);
  if (!prodObj) return;

  if (PM.productoEstaAgotado(prodObj)) {
    alert('Este producto está agotado.');
    return;
  }

  if (productoPermitePersonalizacion(prodObj)) {
    abrirModalPersonalizacion(prodObj);
    return;
  }

  const precioBase = obtenerPrecioProducto(prodObj, cartaActualSucursalId);
  const lineaExistente = CARRITO.find(i =>
    i.productoBaseId === prodObj.id &&
    !i.variacion &&
    (!i.adicionalesLista || i.adicionalesLista.length === 0)
  );

  if (lineaExistente) {
    lineaExistente.cantidad += 1;
  } else {
    CARRITO.push({
      id: `${prodObj.id}_simple_${Date.now()}`,
      claveConfig: `${prodObj.id}|base|`,
      productoBaseId: prodObj.id,
      categoriaId: prodObj.categoria,
      nombre: prodObj.nombre,
      variacion: null,
      precio: precioBase,
      cantidad: 1,
      detallesExtras: [],
      adicionalesLista: []
    });
  }
  actualizarVistaCarrito();
}

